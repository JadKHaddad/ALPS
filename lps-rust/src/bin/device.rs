//! This is a device simulator that acts like a device.
//!
//! The device generates events at a fixed interval and pushes them to the server. If the push fails, it will retry after a fixed duration.
//!
//! ```not_rust
//!
//! cargo run -r --bin device -- --config-file device-config.yaml
//!
//! ```

use std::{path::PathBuf, time::Duration};

use anyhow::Context;
use lps_rust::SimpleCall;
use rand::RngExt;
use serde::Deserialize;

use clap::Parser;

#[derive(Debug, Parser)]
pub struct Args {
    #[clap(long, default_value = "device-config.yaml")]
    /// Config file: The path to the configuration file
    config_file: PathBuf,
}

fn default_devices_count() -> u32 {
    10
}

fn default_server_push_url() -> String {
    String::from("http://localhost:8080/work")
}

fn default_max_event_interval() -> Duration {
    Duration::from_secs(5)
}

fn default_retry_duration() -> Duration {
    Duration::from_millis(500)
}

#[derive(Debug, Clone, Deserialize)]
struct Config {
    /// The number of devices to simulate.
    #[serde(default = "default_devices_count")]
    devices_count: u32,
    #[serde(default = "default_server_push_url")]
    server_push_url: String,
    /// The maximum interval between two events being generated by the device. The actual interval will be a random value between 0 and this value.
    #[serde(default = "default_max_event_interval", with = "humantime_serde")]
    max_event_interval: Duration,
    /// The maximum number of events to generate for each device. If not set, the device will generate events indefinitely.
    #[serde(default)]
    max_events: Option<u64>,
    /// How long should the device wait before retrying to push an event if the previous attempt fails
    #[serde(default = "default_retry_duration", with = "humantime_serde")]
    retry_duration: Duration,
}

impl Default for Config {
    fn default() -> Self {
        Self {
            devices_count: default_devices_count(),
            server_push_url: default_server_push_url(),
            max_event_interval: default_max_event_interval(),
            max_events: None,
            retry_duration: default_retry_duration(),
        }
    }
}

impl Config {
    async fn load_from_file(path: &PathBuf) -> anyhow::Result<Self> {
        serde_yaml::from_slice(
            &tokio::fs::read(path)
                .await
                .context("Failed to read config file")?,
        )
        .context("Failed to deserialize config file")
    }

    /// Returns an iterator of event ids to generate for each device.
    ///
    /// - If `max_events` is set, the iterator will generate event ids from 0 to `max_events - 1`.
    /// - If `max_events` is not set, the iterator will generate event ids indefinitely.
    fn iter(&self) -> impl Iterator<Item = u64> + Send + 'static {
        self.max_events
            .map(|max| Box::new(0..max) as Box<dyn Iterator<Item = u64> + Send>)
            .unwrap_or(Box::new(std::iter::repeat(0u64)) as Box<dyn Iterator<Item = u64> + Send>)
    }
}

#[tokio::main]
async fn main() -> Result<(), anyhow::Error> {
    let filter = tracing_subscriber::EnvFilter::try_from_default_env()
        .or_else(|_| tracing_subscriber::EnvFilter::try_new("device=info"))?;

    tracing_subscriber::fmt().with_env_filter(filter).init();

    let args = Args::parse();

    let config = Config::load_from_file(&args.config_file)
        .await
        .unwrap_or_else(|err| {
            tracing::error!("Failed to load config: {}", err);
            tracing::warn!("Using default configuration");

            Config::default()
        });

    tracing::info!(?config, "Starting");

    let tasks: Vec<_> = (0..config.devices_count)
        .map(|id| {
            let config = config.clone();

            tokio::spawn(async move {
                let client = reqwest::Client::new();

                for i in config.iter() {
                    let max_ms = config.max_event_interval.as_millis();

                    let duration_ms = if max_ms == 0 {
                        0
                    } else {
                        rand::rng().random_range(0..max_ms) as u64
                    };

                    tokio::time::sleep(Duration::from_millis(duration_ms)).await;

                    let call = SimpleCall::new_now(id.to_string());

                    let mut try_index = 0;

                    'work: loop {
                        try_index += 1;

                        // The request id is not used in our system
                        let request_id = format!("device-{}-event-{}-try-{}", id, i, try_index);

                        tracing::info!(request_id, ?call, "Sending work request");

                        let response = client
                            .post(&config.server_push_url)
                            .header("request-id", request_id.clone())
                            .json(&call)
                            .send()
                            .await;

                        match response {
                            Ok(response) if response.status().is_success() => {
                                tracing::info!(request_id, ?call, "Work succeeded");

                                break 'work;
                            }
                            Ok(response) => {
                                tracing::warn!(request_id, status=%response.status(), ?call, "Work failed");

                                tokio::time::sleep(config.retry_duration).await;

                                continue 'work;
                            }
                            Err(err) => {
                                tracing::warn!(request_id, %err, ?call, "Work failed");

                                tokio::time::sleep(config.retry_duration).await;

                                continue 'work;
                            }
                        }
                    }
                }
            })
        })
        .collect();

    for task in tasks {
        task.await?;
    }

    Ok(())
}
